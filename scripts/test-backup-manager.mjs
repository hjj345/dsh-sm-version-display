import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, existsSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { deleteBackups, isBackupComplete, listBackups, registerBackup, validateBackupDirectory } from '../lib/backup-manager.mjs';

const fixture = mkdtempSync(join(tmpdir(), 'dsh-backup-manager-test-'));
try {
  const stateDir = join(fixture, 'state'), source = join(fixture, 'source'), custom = join(fixture, 'custom');
  mkdirSync(source);
  assert.throws(() => validateBackupDirectory(join(source, 'nested'), [source]), /overlaps/);
  assert.throws(() => validateBackupDirectory(fixture, [source]), /overlaps/);
  assert.equal(validateBackupDirectory(custom, [source]), custom);
  const root = join(custom, '1790169017275-2fbc64a583964bc494be4002');
  const backup = { root, global: join(root, 'global'), dsh: join(root, 'dsh'), status: 'complete' };
  mkdirSync(backup.global, { recursive: true }); mkdirSync(backup.dsh);
  writeFileSync(join(backup.global, 'data'), 'hello');
  writeFileSync(join(root, 'manifest.json'), JSON.stringify({ state: { id: 'job' }, backup }));
  registerBackup(stateDir, { path: root, createdAt: 1 });
  assert.equal(isBackupComplete(backup, 'job'), true);
  assert.equal(isBackupComplete(backup, 'other'), false);
  assert.throws(() => validateBackupDirectory(join(root, 'nested')), /inside-backup/);
  const outside = join(source, 'retain'); writeFileSync(outside, 'do not remove');
  symlinkSync(source, join(backup.global, 'link'), process.platform === 'win32' ? 'junction' : 'dir');
  const listed = await listBackups(stateDir);
  assert.equal(listed.backups.length, 1); assert.equal(listed.backups[0].status, 'complete');
  assert.equal(listed.backups[0].fileCount, 2);
  const fastListed = await listBackups(stateDir, undefined, { measureSizes: false });
  assert.equal(fastListed.backups[0].sizeBytes, null);
  assert.equal(fastListed.backups[0].fileCount, null);
  await assert.rejects(deleteBackups(stateDir, [root], { status: 'running', backup }), /running/);
  assert.equal((await deleteBackups(stateDir, [source])).errors.length, 1);
  assert.deepEqual((await deleteBackups(stateDir, [root])).deleted, [root]);
  assert.equal(existsSync(outside), true);
  const incomplete = join(stateDir, 'backups', '1790169017275-aaaaaaaaaaaaaaaaaaaaaaaa');
  mkdirSync(incomplete, { recursive: true }); writeFileSync(join(incomplete, 'partial'), '123');
  assert.equal((await listBackups(stateDir)).backups[0].status, 'incomplete');
  assert.equal((await listBackups(stateDir)).backups[0].sizeBytes, 3);
  const manifestBackup = join(stateDir, 'backups', '1789395768556-fc01ffddaa03518da38fcc85');
  mkdirSync(join(manifestBackup, 'global'), { recursive: true }); mkdirSync(join(manifestBackup, 'dsh'));
  const saved = { root: manifestBackup, global: join(manifestBackup, 'global'), dsh: join(manifestBackup, 'dsh'), status: 'complete', files: 1331687, bytes: 16737460781 };
  writeFileSync(join(manifestBackup, 'manifest.json'), JSON.stringify({ state: { id: 'large-job' }, backup: saved }));
  const afterLarge = await listBackups(stateDir);
  assert.equal(afterLarge.backups.find(item => item.id === manifestBackup).sizeBytes, saved.bytes);
  const interrupted = join(stateDir, 'backups', '1790169017275-aaaaaaaaaaaaaaaaaaaaaaaa');
  const failedState = { id: 'failed-job', status: 'error', backup: { root: interrupted, global: join(interrupted, 'global'), dsh: join(interrupted, 'dsh'), status: 'error', copiedBytes: 1234, completedFiles: 17 } };
  mkdirSync(failedState.backup.global, { recursive: true }); mkdirSync(failedState.backup.dsh);
  const afterFailed = await listBackups(stateDir, failedState);
  assert.equal(afterFailed.backups.find(item => item.id === interrupted).sizeBytes, 1234);
  assert.equal(afterFailed.backups.find(item => item.id === interrupted).status, 'failed');
  console.log('backup manager checks passed');
} finally { rmSync(fixture, { recursive: true, force: true }); }
